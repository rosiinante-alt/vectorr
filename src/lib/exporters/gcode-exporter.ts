import { BaseExporter, type ExportOptions } from './base-exporter';
import { extractShapes, getDimensions } from './svg-utils';

/**
 * Laser-cutter G-code (GRBL-flavoured).
 *
 * Uses the same millimetre mapping as the DXF exporter so a job cut from either
 * format lands at the same physical size. Closed regions are cut once; each
 * path starts with the laser off, moves, then cuts, and ends with `M5` so a
 * failed midpoint never leaves the beam on.
 */
export class GcodeExporter extends BaseExporter {
  format = 'gcode';

  async export(svgContent: string, options?: ExportOptions): Promise<string> {
    const { height, minX, minY } = getDimensions(svgContent, options);
    const mmPerUnit = 25.4 / (options?.dpi ?? 96);
    const feedRate = 1000;

    const lines = [
      '; Generated by Vectroy',
      '; Units: millimetres',
      'G21 ; mm',
      'G90 ; absolute positioning',
      'M5 ; laser off',
      'G28 ; home',
    ];

    const coord = (point: { x: number; y: number }) =>
      `X${((point.x - minX) * mmPerUnit).toFixed(3)} Y${((height - (point.y - minY)) * mmPerUnit).toFixed(3)}`;

    for (const shape of extractShapes(svgContent)) {
      const points = shape.points;
      if (points.length < 2) continue;

      lines.push(`G0 ${coord(points[0])} ; travel`, 'M3 S1000 ; laser on');
      for (const point of points.slice(1)) {
        lines.push(`G1 ${coord(point)} F${feedRate}`);
      }
      if (shape.closed) {
        lines.push(`G1 ${coord(points[0])} F${feedRate} ; close`);
      }
      lines.push('M5 ; laser off');
    }

    lines.push('G0 X0 Y0', 'M5', 'M2 ; program end');
    return lines.join('\n') + '\n';
  }
}
