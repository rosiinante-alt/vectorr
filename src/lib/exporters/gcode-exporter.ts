import { BaseExporter, type ExportOptions } from './base-exporter';
import { extractShapes, getDimensions } from './svg-utils';

export class GcodeExporter extends BaseExporter {
  format = 'gcode';
  async export(svgContent: string, options?: ExportOptions): Promise<string> {
    const { height, minX, minY } = getDimensions(svgContent, options);
    const scale = 25.4 / (options?.dpi ?? 96);
    const lines = ['; Generated by Vectorr', 'G90 ; Absolute positioning', 'G21 ; Millimeter units', 'G28 ; Home', 'M5 ; Laser off'];
    for (const shape of extractShapes(svgContent)) {
      if (!shape.points.length) continue;
      const coord = (point: {x:number;y:number}) => `X${((point.x-minX)*scale).toFixed(3)} Y${((height-(point.y-minY))*scale).toFixed(3)}`;
      lines.push(`G0 ${coord(shape.points[0])} ; Move`, 'M3 ; Laser on');
      for (const point of shape.points.slice(1)) lines.push(`G1 ${coord(point)} F100 ; Cut`);
      if (shape.closed) lines.push(`G1 ${coord(shape.points[0])} F100 ; Close path`);
      lines.push('M5 ; Laser off');
    }
    lines.push('G28 ; Home');
    return lines.join('\n') + '\n';
  }
}
